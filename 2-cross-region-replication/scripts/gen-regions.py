#!/usr/bin/env python3
"""Generate infra/regions.generated.tf from regions.json.

Terraform cannot iterate provider configurations, so each replica region needs
an explicit provider alias and an explicit module call. Keep regions.json as
the single source of truth and regenerate instead of editing by hand.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[1]
cfg = json.loads((root / "regions.json").read_text())
alias = lambda r: r.replace("-", "_")

out = ["# GENERATED by scripts/gen-regions.py from regions.json. Do not edit.", ""]

for r in cfg["replicas"]:
    out += [
        f'provider "aws" {{',
        f'  alias               = "{alias(r["id"])}"',
        f'  region              = "{r["id"]}"',
        f"  allowed_account_ids = [var.account_id]",
        f"  default_tags {{ tags = local.tags }}",
        f"}}",
        "",
    ]

for r in cfg["replicas"]:
    out += [
        f'module "replica_{alias(r["id"])}" {{',
        f'  source    = "./modules/replica"',
        f"  providers = {{ aws = aws.{alias(r['id'])} }}",
        "",
        f"  project            = local.project",
        f'  region             = "{r["id"]}"',
        f"  bucket_name        = \"${{local.bucket_prefix}}-{r['id']}\"",
        f"  central_bus_arn    = aws_cloudwatch_event_bus.central.arn",
        f"  forward_role_arn   = aws_iam_role.event_forward.arn",
        f"  probe_role_arn     = aws_iam_role.probe.arn",
        f"  probe_zip          = data.archive_file.probe.output_path",
        f"  probe_zip_hash     = data.archive_file.probe.output_base64sha256",
        f"  replica_expiry_days = var.replica_expiry_days",
        f"}}",
        "",
    ]

out += [
    "locals {",
    "  replica_buckets = {",
]
for r in cfg["replicas"]:
    out.append(f'    "{r["id"]}" = module.replica_{alias(r["id"])}.bucket_name')
out += ["  }", "  replica_bucket_arns = {"]
for r in cfg["replicas"]:
    out.append(f'    "{r["id"]}" = module.replica_{alias(r["id"])}.bucket_arn')
out += ["  }", "  probe_function_arns = {"]
for r in cfg["replicas"]:
    out.append(f'    "{r["id"]}" = module.replica_{alias(r["id"])}.probe_arn')
out += ["  }", "}", ""]

(root / "infra" / "regions.generated.tf").write_text("\n".join(out))
print(f"wrote infra/regions.generated.tf for {len(cfg['replicas'])} regions")
